async function getConfig(): Promise<ExtConfig> {
  const got = await chrome.storage.local.get('config');
  return { ...DEFAULT_CONFIG, ...(got.config ?? {}) };
}

// Toolbar icon: grey square with a white R (dist/icons, generated by the
// build). The only deviations live bottom-right: orange ! when the server is
// unreachable (global), red stop octagon on tabs whose site is blocked. When
// both apply the server error wins — a blocked page is expected, a dead server
// means nothing is being recorded anywhere.
const ICONS: Record<'base' | 'err' | 'stop', { [size: number]: string }> = {
  base: {
    16: 'dist/icons/icon16-base.png',
    32: 'dist/icons/icon32-base.png',
    48: 'dist/icons/icon48-base.png',
    128: 'dist/icons/icon128-base.png',
  },
  err: {
    16: 'dist/icons/icon16-err.png',
    32: 'dist/icons/icon32-err.png',
    48: 'dist/icons/icon48-err.png',
    128: 'dist/icons/icon128-err.png',
  },
  stop: {
    16: 'dist/icons/icon16-stop.png',
    32: 'dist/icons/icon32-stop.png',
    48: 'dist/icons/icon48-stop.png',
    128: 'dist/icons/icon128-stop.png',
  },
};

type TabStatus = 'saved' | 'blocked' | 'password' | 'thin' | 'filtered';

interface TabEntry {
  status: TabStatus;
  title: string;
}

// Per-tab feedback lives in storage.session so the popup can read it. Tab
// icons override the global icon, so every state change re-derives the icon
// from (serverOk, tab status) instead of remembering what is drawn.
async function tabStates(): Promise<Record<string, TabEntry>> {
  const { tabState } = (await chrome.storage.session.get('tabState')) as {
    tabState?: Record<string, TabEntry>;
  };
  return tabState ?? {};
}

async function serverOk(): Promise<boolean> {
  const { serverOk: ok } = (await chrome.storage.session.get('serverOk')) as { serverOk?: boolean };
  return ok !== false;
}

async function applyTabIcon(tabId: number): Promise<void> {
  const [ok, states] = await Promise.all([serverOk(), tabStates()]);
  const entry = states[tabId];
  const kind = !ok ? 'err' : entry?.status === 'blocked' ? 'stop' : 'base';
  chrome.action.setIcon({ tabId, path: ICONS[kind] });
  chrome.action.setTitle({
    tabId,
    title: entry?.title ?? (!ok ? 'iRecall: server not reachable' : 'iRecall'),
  });
}

async function refreshChrome(): Promise<void> {
  const [ok, cfg] = await Promise.all([serverOk(), getConfig()]);
  chrome.action.setIcon({ path: ICONS[ok ? 'base' : 'err'] });
  chrome.action.setTitle({
    title: !ok ? 'iRecall: server not reachable' : cfg.enabled ? 'iRecall' : 'iRecall: paused',
  });
  for (const tabId of Object.keys(await tabStates())) await applyTabIcon(Number(tabId));
}

async function setServerOk(ok: boolean): Promise<void> {
  if ((await serverOk()) === ok) return;
  await chrome.storage.session.set({ serverOk: ok });
  await refreshChrome();
}

async function setTabEntry(tabId: number, status: TabStatus, title: string): Promise<void> {
  const states = await tabStates();
  states[tabId] = { status, title };
  await chrome.storage.session.set({ tabState: states });
  await applyTabIcon(tabId);
}

async function clearTabEntry(tabId: number): Promise<void> {
  const states = await tabStates();
  delete states[tabId];
  await chrome.storage.session.set({ tabState: states });
  await applyTabIcon(tabId);
}

// --- capture buffer ---------------------------------------------------------

// Buffer entries carry a per-session sequence number: the flush trim removes
// by identity (seq > lastSentSeq), not by stale count, so a capture landing
// mid-flush is never overwritten.
interface BufferItem {
  seq: number;
  page: CaptureMsg['page'];
  // Which tab produced the capture — lets the flush verdict (filtered) land
  // back on the right tab's popup state. Optional: legacy buffers lack it.
  tabId?: number;
}

// chrome.storage.session quota is ~10MB; 50 pages with a 2MB worst case each
// is too big, but real captures run ~10-100KB — 50 keeps days of headroom.
// Overflow drops oldest (logged).
const MAX_BUFFER = 50;

// Legacy 0.1.x buffers stored bare page objects; wrap them so the seq-based
// trim sees a consistent shape.
function asItems(raw: unknown): BufferItem[] {
  const arr = Array.isArray(raw) ? raw : [];
  return arr.map((b) => {
    const item = b as Partial<BufferItem> & Record<string, unknown>;
    if (item && typeof item === 'object' && item.page && typeof item.seq === 'number') {
      return item as BufferItem;
    }
    return { seq: 0, page: item as unknown as CaptureMsg['page'] };
  });
}

// Serialize all buffer reads/writes: concurrent captures would race the
// get→set window and silently lose one. Single FIFO, never poisoned.
let enqueueChain: Promise<void> = Promise.resolve();

function enqueue(page: CaptureMsg['page'], tabId?: number): void {
  enqueueChain = enqueueChain.then(() => reallyEnqueue(page, tabId)).catch(() => {});
}

async function reallyEnqueue(page: CaptureMsg['page'], tabId?: number): Promise<void> {
  const { buffer } = (await chrome.storage.session.get('buffer')) as { buffer?: unknown };
  const items = asItems(buffer);
  const seq = (items.length > 0 ? items[items.length - 1]!.seq : 0) + 1;
  let next: BufferItem[] = [...items, { seq, page, tabId }];
  if (next.length > MAX_BUFFER) {
    const droppedCount = next.length - MAX_BUFFER;
    next = next.slice(droppedCount);
    void log('error', `buffer full, dropped ${droppedCount} oldest page(s)`);
  }
  try {
    await chrome.storage.session.set({ buffer: next });
  } catch (err) {
    void log('error', `buffer write failed: ${err instanceof Error ? err.message : 'quota'}`);
    return;
  }
  let host = page.url;
  try {
    host = new URL(page.url).hostname;
  } catch {
    // keep raw url as detail
  }
  void log('capture', `${host} — ${(page.title ?? '').slice(0, 60)}`);
  if (next.length >= FLUSH_AT) void flush();
  else chrome.alarms.create(FLUSH_ALARM, { delayInMinutes: 0.5 });
}

// Pre-wiring: pulls the local token from the server so the user never pastes it.
// Success/failure also feeds the toolbar icon's "server unreachable" state.
async function fetchBootstrap(): Promise<boolean> {
  try {
    // Client header lets the server tell extension pings apart from the
    // tray's own /bootstrap + /config polling (drives its setup warning).
    const res = await fetch(`${SERVER}/bootstrap`, {
      headers: { 'x-irecall-client': 'extension' },
      signal: AbortSignal.timeout(5_000),
    });
    if (!res.ok) throw new Error(String(res.status));
    const data = (await res.json()) as { token?: string };
    if (typeof data.token === 'string' && data.token.length > 0) {
      await chrome.storage.local.set({ token: data.token });
      void setServerOk(true);
      void log('config', 'server connected');
      return true;
    }
  } catch {
    // fall through to the unreachable path
  }
  void setServerOk(false);
  return false;
}

// Single-flight: overlapping flushes would each POST the same snapshot and a
// stale-count trim could drop pages enqueued mid-flight. One at a time;
// suppressed callers re-arm the alarm. SW termination mid-flight just resets
// the flag — worst case a duplicate POST, which server-side dedup absorbs.
let flushing = false;

async function flush(): Promise<void> {
  if (flushing) {
    chrome.alarms.create(FLUSH_ALARM, { delayInMinutes: 0.5 });
    return;
  }
  flushing = true;
  try {
    await doFlush();
  } finally {
    flushing = false;
  }
}

async function doFlush(): Promise<void> {
  const { buffer: rawBuf } = (await chrome.storage.session.get('buffer')) as { buffer?: unknown };
  const buffer = asItems(rawBuf);
  if (buffer.length === 0) return;
  let { token } = (await chrome.storage.local.get('token')) as { token?: string };
  if (!token) {
    if (!(await fetchBootstrap())) {
      // server unreachable: retry later, keep buffer
      chrome.alarms.create(FLUSH_ALARM, { delayInMinutes: 1 });
      return;
    }
    token = ((await chrome.storage.local.get('token')) as { token?: string }).token;
  }
  try {
    const res = await fetch(`${SERVER}/ingest`, {
      method: 'POST',
      headers: { 'content-type': 'application/json', authorization: `Bearer ${token}` },
      body: JSON.stringify({ pages: buffer.map((b) => b.page) }),
      signal: AbortSignal.timeout(10_000),
    });
    if (res.status === 401) {
      // stale token (server regenerated .token): refresh, retry via alarm
      await chrome.storage.local.remove('token');
      await fetchBootstrap();
      chrome.alarms.create(FLUSH_ALARM, { delayInMinutes: 1 });
      return;
    }
    if (!res.ok) throw new Error(`status ${res.status}`);
    // The ingest verdict is the honest feedback: saved, duplicates skipped,
    // off-focus pages filtered by rules, pre-pause pages dropped.
    const out = (await res.json()) as {
      inserted?: number;
      skipped?: number;
      filtered?: number;
      filteredPages?: { url?: string; domain: string }[];
      dropped?: number;
    };
    const parts: string[] = [`${out.inserted ?? 0} saved`];
    if (out.filtered) parts.push(`${out.filtered} off-focus`);
    if (out.skipped) parts.push(`${out.skipped} duplicate`);
    if (out.dropped) parts.push(`${out.dropped} pre-pause`);
    void log('sync', parts.join(', '));
    for (const fp of (out.filteredPages ?? []).slice(0, 5)) {
      void log('skip', `off-focus: ${fp.domain}`);
      // Land the verdict on the tab that produced the page, so the popup says
      // "kept out by the focus filter" instead of a generic "not captured".
      const sent = buffer.find((b) => b.page.url === fp.url);
      if (sent?.tabId != null) {
        void setTabEntry(sent.tabId, 'filtered', 'iRecall: focus filter kept this out');
      }
    }
    const lastSeq = buffer[buffer.length - 1]!.seq;
    const { buffer: now } = (await chrome.storage.session.get('buffer')) as { buffer?: unknown };
    await chrome.storage.session.set({ buffer: asItems(now).filter((b) => b.seq > lastSeq) });
    void setServerOk(true);
  } catch (err) {
    void setServerOk(false);
    void log('error', `sync failed: ${err instanceof Error ? err.message : 'network'}`);
    chrome.alarms.create(FLUSH_ALARM, { delayInMinutes: 1 });
  }
}

// Server is the source of truth for the recording flag (tray + dashboard +
// popup all write it there); extension mirrors it into chrome.storage.
// Also syncs the early-filter feedback list: domains the server keeps
// rejecting get ignored at the source (no Readability work, no capture).
async function syncRecording(): Promise<void> {
  const { token } = (await chrome.storage.local.get('token')) as { token?: string };
  if (!token) return;
  try {
    const res = await fetch(`${SERVER}/config`, {
      headers: { authorization: `Bearer ${token}`, 'x-irecall-client': 'extension' },
      signal: AbortSignal.timeout(5_000),
    });
    if (!res.ok) return;
    void setServerOk(true); // authenticated answer = server is up
    const data = (await res.json()) as { recording?: boolean };
    if (typeof data.recording !== 'boolean') return;
    const { config } = (await chrome.storage.local.get('config')) as { config?: ExtConfig };
    const enabledNow = config?.enabled !== false;
    if (data.recording !== enabledNow) {
      await chrome.storage.local.set({ config: { ...DEFAULT_CONFIG, ...config, enabled: data.recording } });
      void log(data.recording ? 'resumed' : 'paused', data.recording ? 'recording resumed' : 'recording paused');
    }
  } catch {
    // server down: keep last known state
  }
  try {
    const fl = await fetch(`${SERVER}/api/filterlist`, {
      headers: { authorization: `Bearer ${token}` },
      signal: AbortSignal.timeout(5_000),
    });
    if (fl.ok) {
      const data = (await fl.json()) as { domains?: unknown };
      if (Array.isArray(data.domains)) {
        await chrome.storage.local.set({ filterlist: { domains: data.domains } });
      }
    }
  } catch {
    // filterlist is advisory; ignore failures
  }
  // Mirror the user blocklist (popup + dashboard both write it server-side).
  try {
    const bl = await fetch(`${SERVER}/api/blocked`, {
      headers: { authorization: `Bearer ${token}` },
      signal: AbortSignal.timeout(5_000),
    });
    if (bl.ok) {
      const data = (await bl.json()) as { domains?: { domain?: unknown }[] };
      const domains = (data.domains ?? [])
        .map((d) => (d && typeof d === 'object' ? d.domain : null))
        .filter((d): d is string => typeof d === 'string');
      await chrome.storage.local.set({ blocked: { domains } });
    }
  } catch {
    // advisory mirror; local state still applies until the next sync
  }
}

// --- wiring -----------------------------------------------------------------

chrome.runtime.onMessage.addListener((msg: CaptureMsg | StateMsg, sender) => {
  if (msg.type === 'capture' && 'page' in msg) {
    const tabId = sender.tab?.id;
    if (tabId != null) {
      const at = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
      void setTabEntry(tabId, 'saved', `iRecall: saved this page (${at})`);
      // Fade "saved" so it marks "this page was just captured", not a permanent
      // state. If the worker dies early the entry lasts until the next capture
      // message from that tab overwrites it anyway.
      void (async () => {
        await new Promise((r) => setTimeout(r, 2500));
        const states = await tabStates();
        if (states[tabId]?.status === 'saved') await clearTabEntry(tabId);
      })();
    }
    enqueue(msg.page, tabId);
  } else if (msg.type === 'state' && 'state' in msg && msg.state === 'skipped' && sender.tab?.id != null) {
    const tabId = sender.tab.id;
    const label =
      msg.reason === 'blocked'
        ? 'site blocked'
        : msg.reason === 'password'
          ? 'login page, skipped'
          : 'too little readable text';
    void setTabEntry(tabId, msg.reason, `iRecall: ${label}`);
    void log('skip', `${label}: ${msg.host}`);
  }
});

chrome.alarms.onAlarm.addListener((a) => {
  if (a.name === FLUSH_ALARM) void flush();
  if (a.name === SYNC_ALARM) void syncRecording();
});

chrome.runtime.onInstalled.addListener(() => {
  void (async () => {
    const got = await chrome.storage.local.get('config');
    if (!got.config) await chrome.storage.local.set({ config: DEFAULT_CONFIG });
    // Fresh load: grab the token now instead of waiting for the first flush
    // (which only bootstraps when the buffer is non-empty).
    await fetchBootstrap();
    await refreshChrome();
    chrome.alarms.create(SYNC_ALARM, { periodInMinutes: 1 });
  })();
});

chrome.runtime.onStartup.addListener(() => {
  // Server may have regenerated .token while Chrome was closed.
  void fetchBootstrap();
  void refreshChrome();
  chrome.alarms.create(SYNC_ALARM, { periodInMinutes: 1 });
});

chrome.storage.onChanged.addListener((changes, area) => {
  if (area !== 'local') return;
  if (changes.config) void refreshChrome();
});

void refreshChrome();

