// MV3 service worker: buffers captures in storage.session, flushes to the
// local server with bearer token, renders toolbar icon state.
const SERVER = 'http://127.0.0.1:8787';
const FLUSH_AT = 5;
const FLUSH_ALARM = 'flush';
const SYNC_ALARM = 'sync';

interface ExtConfig {
  enabled: boolean;
  blockedDomains: string[];
  allowedDomains: string[];
}

interface CaptureMsg {
  type: 'capture';
  page: {
    url: string;
    title: string | null;
    content: string;
    excerpt: string | null;
    byline: string | null;
    dwellMs: number;
    capturedAt: number;
    reason?: string;
  };
}
type StateMsg = {
  type: 'state';
  state: 'skipped';
  host: string;
  reason: 'blocked' | 'password' | 'thin';
};

interface LogEntry {
  ts: number;
  kind: string;
  detail: string;
}

const LOG_CAP = 200;

async function log(kind: string, detail: string): Promise<void> {
  const { logs = [] } = (await chrome.storage.local.get('logs')) as { logs?: LogEntry[] };
  logs.unshift({ ts: Date.now(), kind, detail });
  await chrome.storage.local.set({ logs: logs.slice(0, LOG_CAP) });
}

